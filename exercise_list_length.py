def list_length(lista):
    """
    Retorna la cantidad de elementos presentes en la lista dada.
    
    Parámetros:
    lista (list): Una lista con cualquier tipo de elementos.
    
    Retorna:
    int: El número total de elementos en la lista.
    """
    # Usamos la función interna len() para obtener el tamaño de la lista
    # y usamos 'return' en lugar de 'print' porque el test evalúa el valor devuelto.
    return len(lista)